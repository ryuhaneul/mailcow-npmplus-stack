#!/bin/bash
# Verified common-template overlay; use the existing WAF/archive Compose runners.
NPMPLUS_ACME_LIB_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
NPMPLUS_ACME_DIGEST=sha256:f7f6ca26082036ee6387a7da336267fe61f16b1eb8087dd964237238b59479ef
NPMPLUS_ACME_SOURCE_SHA256=a97ffe67ff769df42fec6be915bf0dc0476492e57a33189b9b54388fec55c8e7

npmplus_acme_error() { echo "[acme80] ERROR: $*" >&2; return 1; }
npmplus_acme_compose() {
    if declare -F _waf_npmplus_compose >/dev/null; then _waf_npmplus_compose "$@"
    else docker compose "$@"; fi
}

npmplus_acme_lock() {
    [ -z "${NPMPLUS_ACME_LOCK_FD:-}" ] || return 0
    local key
    key=$(printf '%s' "$(realpath -m "$1")" | sha256sum) || return 1
    # Hold through prepare, container replacement, API verification and rollback.
    exec {NPMPLUS_ACME_LOCK_FD}>"/run/lock/npmplus-acme80-${key%% *}.lock" || return 1
    flock -n "$NPMPLUS_ACME_LOCK_FD" || { exec {NPMPLUS_ACME_LOCK_FD}>&-; unset NPMPLUS_ACME_LOCK_FD; npmplus_acme_error 'another apply holds the lock'; return 1; }
}

npmplus_acme_guard() {
    local dir="$1" actual image
    image=$(cd "$dir" && npmplus_acme_compose config --format json 2>/dev/null | python3 -c '
import json,pathlib,sys
try:
 c=json.load(sys.stdin)["services"]["npmplus"]
 image=c["image"]
 if image.split("@")[-1]!=sys.argv[1] or "@" not in image: raise ValueError()
 if c.get("environment",{}).get("REGENERATE_ALL") not in (None,"false",False,""): raise ValueError()
 expected=pathlib.Path(sys.argv[2]).resolve()/"templates/_common.conf"
 mounts=[v for v in c.get("volumes",[]) if v.get("target")=="/app/templates/_common.conf"]
 if len(mounts)>1: raise ValueError()
 for v in mounts:
  if v.get("type")!="bind" or pathlib.Path(v["source"]).resolve()!=expected or v.get("read_only") is not True: raise ValueError()
  if v.get("bind",{}).get("create_host_path") is not False or not expected.is_file(): raise ValueError()
 print(image)
except (ValueError,KeyError,TypeError): sys.exit(1)
' "$NPMPLUS_ACME_DIGEST" "$dir") || { npmplus_acme_error 'image digest or existing mount conflict; no ACME changes applied'; return 1; }
    docker image inspect "$image" >/dev/null 2>&1 || (cd "$dir" && npmplus_acme_compose pull npmplus >/dev/null 2>&1) || {
        npmplus_acme_error 'cannot fetch pinned image'; return 1;
    }
    actual=$(docker run --rm --network none --read-only --entrypoint sha256sum "$image" /app/templates/_common.conf 2>/dev/null) || return 1
    [ "${actual%% *}" = "$NPMPLUS_ACME_SOURCE_SHA256" ] || {
        npmplus_acme_error 'image common-template SHA256 mismatch; review image before applying'; return 1;
    }
    python3 - "$NPMPLUS_ACME_LIB_DIR/../../npmplus/templates/_common.conf" "$NPMPLUS_ACME_SOURCE_SHA256" <<'PY' || return 1
import hashlib,pathlib,sys
try:
 raw=pathlib.Path(sys.argv[1]).read_bytes()
 block=b'    if ($request_uri ~ ^/\\.well-known/acme-challenge/) {\n      break;\n    }\n'
 needle=b'  {% if ssl_forced %}\n'+block
 if raw.count(block)!=1 or raw.count(needle)!=1 or hashlib.sha256(raw.replace(block,b'',1)).hexdigest()!=sys.argv[2]:
  raise ValueError()
except (OSError,ValueError): sys.exit('[acme80] ERROR: patched template differs from approved source')
PY
    NPMPLUS_ACME_IMAGE="$image"
}

npmplus_acme_preflight() {
    local dir="$1" first
    npmplus_acme_lock "$dir" || return 1
    npmplus_acme_guard "$dir" || return 1
    [ ! -L "$dir/templates" ] || { npmplus_acme_error "unsafe template directory"; return 1; }
    [ -n "${NPM_ADMIN_EMAIL:-}" ] && [ -n "${NPM_ADMIN_PASSWORD:-}" ] || {
        npmplus_acme_error 'existing NPM admin credentials required'; return 1;
    }
    if [ -e "$dir/docker-compose.override.yml" ]; then
        [ -f "$dir/docker-compose.override.yml" ] && [ ! -L "$dir/docker-compose.override.yml" ] || return 1
        IFS= read -r first < "$dir/docker-compose.override.yml" || true
        [ "$first" = '# Generated by scripts/lib/edge.sh' ] || {
            npmplus_acme_error 'unmanaged override; refusing to replace'; return 1;
        }
    fi
    if docker inspect npmplus >/dev/null 2>&1; then
        docker exec npmplus nginx -t >/dev/null 2>&1 || return 1
        # docker exec's environment lacks defaults exported by envs.sh. Inspect the
        # running backend's environment, using the image's exact env+TV algorithm.
        (cd "$dir" && npmplus_acme_compose config --format json 2>/dev/null) | docker exec -i npmplus node --input-type=module -e '
import fs from "node:fs"; import crypto from "node:crypto";
let env;
for (const id of fs.readdirSync("/proc").filter(v=>/^\d+$/.test(v))) {
 try {
  const args=fs.readFileSync(`/proc/${id}/cmdline`,"utf8").split("\0");
  if (!args.some(a=>/(^|\/)index\.js$/.test(a))) continue;
  env=Object.fromEntries(fs.readFileSync(`/proc/${id}/environ`,"utf8").split("\0").filter(Boolean).map(v=>{const i=v.indexOf("=");return [v.slice(0,i),v.slice(i+1)];}));
  break;
 } catch {}
}
if (!env) process.exit(1);
const refs=new Set();
for(const file of fs.readdirSync("/app/templates")) for(const m of fs.readFileSync("/app/templates/"+file,"utf8").matchAll(/env\.([A-Z0-9_]+)/g)) refs.add(m[1]);
const desired=JSON.parse(fs.readFileSync(0,"utf8")).services.npmplus.environment||{};
for(const key of refs) if(key in desired && String(desired[key]??"")!==(env[key]||"")) process.exit(1);
const input=[...refs].sort().map(k=>env[k]||"").join("")+(env.TV||"");
const hash=crypto.createHash("sha512").update(input).digest("hex");
if(fs.readFileSync("/data/npmplus/env.sha512sum","utf8").trim()!==hash || env.ACME_PROFILE!==process.argv[1]) process.exit(1);
' "${NPM_ACME_PROFILE-classic}" >/dev/null 2>&1 || {
            npmplus_acme_error 'startup would regenerate all configs; stop for operator review'; return 1;
        }
    fi
}

npmplus_acme_backup() {
    [ -z "${NPMPLUS_ACME_BACKUP:-}" ] || return 0
    NPMPLUS_ACME_BACKUP=$(mktemp -d /root/npmplus-acme80-backup-"$(date +%Y%m%d-%H%M%S)"-XXXXXX) || return 1
    chmod 700 "$NPMPLUS_ACME_BACKUP" || return 1
    echo "[acme80] backup: $NPMPLUS_ACME_BACKUP" >&2
    if docker inspect npmplus >/dev/null 2>&1; then
        (umask 077; docker exec npmplus cat /app/templates/_common.conf > "$NPMPLUS_ACME_BACKUP/running-common.conf") || return 1
    fi
    python3 - "$1" "$NPMPLUS_ACME_BACKUP" "$NPMPLUS_ACME_IMAGE" <<'PY'
import json,os,pathlib,shutil,sys
root,backup=map(pathlib.Path,sys.argv[1:3]); manifest={}
for name in ['docker-compose.override.yml','templates/_common.conf','.acme80-state.json']:
 p=root/name
 if p.is_symlink() or (p.exists() and not p.is_file()): sys.exit('[acme80] ERROR: unsafe managed file')
 manifest[name]=p.exists()
 if p.exists():
  target=backup/name;target.parent.mkdir(mode=0o700,parents=True,exist_ok=True)
  shutil.copy2(p,target);os.chmod(target,0o600)
(backup/'files.json').write_text(json.dumps(manifest));os.chmod(backup/'files.json',0o600)
(backup/'image.txt').write_text(sys.argv[3]+'\n');os.chmod(backup/'image.txt',0o600)
PY
}

npmplus_acme_prepare() {
    local dir="$1"
    npmplus_acme_preflight "$dir" || return 1
    npmplus_acme_backup "$dir" || return 1
    NPMPLUS_ACME_CHANGED=false
    if ! cmp -s "$NPMPLUS_ACME_LIB_DIR/../../npmplus/templates/_common.conf" "$dir/templates/_common.conf"; then
        python3 - "$NPMPLUS_ACME_LIB_DIR/../../npmplus/templates/_common.conf" "$dir" <<'PY' || return 1
import os,pathlib,sys,tempfile
source,root=map(pathlib.Path,sys.argv[1:]);dest=root/'templates'
if dest.is_symlink(): sys.exit('[acme80] ERROR: unsafe template directory')
dest.mkdir(mode=0o755,exist_ok=True)
fd,tmp=tempfile.mkstemp(prefix='._common.',dir=dest)
try:
 with os.fdopen(fd,'wb') as stream: stream.write(source.read_bytes())
 os.chmod(tmp,0o644);os.replace(tmp,dest/'_common.conf')
finally:
 if os.path.exists(tmp): os.unlink(tmp)
PY
        NPMPLUS_ACME_CHANGED=true
    fi
    npmplus_acme_mounted "$dir" || NPMPLUS_ACME_CHANGED=true
}

npmplus_acme_mounted() {
    local dir="$1" mounts actual expected image_id running_id
    image_id=$(docker image inspect "$NPMPLUS_ACME_IMAGE" --format '{{.Id}}' 2>/dev/null) || return 1
    running_id=$(docker inspect npmplus --format '{{.Image}}' 2>/dev/null) || return 1
    [ "$image_id" = "$running_id" ] || return 1
    mounts=$(docker inspect npmplus --format '{{json .Mounts}}' 2>/dev/null) || return 1
    python3 - "$mounts" "$dir" <<'PY' || return 1
import json,pathlib,sys
try:
 items=[m for m in json.loads(sys.argv[1]) if m['Destination']=='/app/templates/_common.conf']
 assert len(items)==1 and items[0]['RW'] is False
 assert pathlib.Path(items[0]['Source']).resolve()==(pathlib.Path(sys.argv[2])/'templates/_common.conf').resolve()
except (ValueError,KeyError,TypeError,AssertionError): sys.exit(1)
PY
    actual=$(docker exec npmplus sha256sum /app/templates/_common.conf 2>/dev/null) || return 1
    expected=$(sha256sum "$dir/templates/_common.conf") || return 1
    [ "${actual%% *}" = "${expected%% *}" ]
}

npmplus_acme_wait() {
    local i health
    for i in $(seq 1 36); do
        health=$(docker inspect npmplus --format '{{.State.Health.Status}}' 2>/dev/null) || health=missing
        [ "$health" != healthy ] || return 0
        sleep 5
    done
    npmplus_acme_error 'NPMplus not healthy after 180 seconds'
}

npmplus_acme_api() (
    set +x
    local mode="$1" backup="$2" work
    [ -n "${NPM_ADMIN_EMAIL:-}" ] && [ -n "${NPM_ADMIN_PASSWORD:-}" ] || return 1
    work=$(mktemp -d) || return 1
    trap 'rm -rf "$work"' EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    umask 077
    NPM_LOGIN_EMAIL="$NPM_ADMIN_EMAIL" NPM_LOGIN_SECRET="$NPM_ADMIN_PASSWORD" \
        python3 -B -c 'import os,json; print(json.dumps({"identity":os.environ["NPM_LOGIN_EMAIL"],"secret":os.environ["NPM_LOGIN_SECRET"]}))' > "$work/login.json" || return 1
    export -n NPM_ADMIN_PASSWORD
    python3 -B "$NPMPLUS_ACME_LIB_DIR/npm_api.py" "$mode" "$work" "${NPM_API:-https://127.0.0.1:81/api}" "$backup"
)

npmplus_acme_verify() {
    npmplus_acme_mounted "$1" && docker exec npmplus nginx -t >/dev/null 2>&1 && \
        npmplus_acme_api acme-verify "${NPMPLUS_ACME_BACKUP:?}"
}

npmplus_acme_failure() {
    npmplus_acme_error "$2" || true
    echo "[acme80] Backup: ${NPMPLUS_ACME_BACKUP:-not-created}" >&2
    if [ -n "${NPMPLUS_ACME_BACKUP:-}" ]; then
        printf '[acme80] Rollback: npmplus_acme_rollback %q %q\n' "$1" "$NPMPLUS_ACME_BACKUP" >&2
    fi
    return 1
}

npmplus_acme_apply() {
    local dir="$1" mode=acme-resave hash
    npmplus_acme_wait && npmplus_acme_mounted "$dir" || { npmplus_acme_failure "$dir" "NPM health or mounted template validation failed"; return 1; }
    hash=$(sha256sum "$dir/templates/_common.conf") || return 1
    if python3 - "$dir/.acme80-state.json" "${hash%% *}" "$NPMPLUS_ACME_DIGEST" <<'PY'
import json,pathlib,sys
try:
 state=json.loads(pathlib.Path(sys.argv[1]).read_text())
 assert state=={'template_sha256':sys.argv[2],'image_digest':sys.argv[3]}
except (OSError,ValueError,AssertionError): sys.exit(1)
PY
    then mode=acme-verify; fi
    npmplus_acme_api "$mode" "$NPMPLUS_ACME_BACKUP" || {
        npmplus_acme_failure "$dir" "partial apply stopped; review host recovery status before full rollback"
        return 1
    }
    [ "$mode" != acme-verify ] || return 0
    python3 - "$dir/.acme80-state.json" "${hash%% *}" "$NPMPLUS_ACME_DIGEST" <<'PY'
import json,os,pathlib,sys,tempfile
path=pathlib.Path(sys.argv[1]);fd,tmp=tempfile.mkstemp(prefix='.acme80-state-',dir=path.parent)
try:
 with os.fdopen(fd,'w') as stream: json.dump({'template_sha256':sys.argv[2],'image_digest':sys.argv[3]},stream)
 os.chmod(tmp,0o600);os.replace(tmp,path)
finally:
 if os.path.exists(tmp): os.unlink(tmp)
PY
}

# Explicit recovery: caller sources the usual stack env/WAF/archive helpers first.
npmplus_acme_rollback() {
    local dir="$1" backup="$2"
    npmplus_acme_lock "$dir" || return 1
    # Restore only if files still match what this attempt wrote. An independent
    # operator edit must be reviewed, never silently overwritten during recovery.
    python3 - "$dir" "$backup" <<'PY' || return 1
import json,os,pathlib,shutil,sys,tempfile
root,backup=map(pathlib.Path,sys.argv[1:]);manifest=json.loads((backup/'files.json').read_text())
written=json.loads((backup/'written.json').read_text())
import hashlib
for name,value in written.items():
 p=root/name
 if p.is_symlink() or not p.is_file() or hashlib.sha256(p.read_bytes()).hexdigest()!=value:
  sys.exit('[acme80] ERROR: managed file changed independently; manual recovery required')
for name,existed in manifest.items():
 p=root/name
 if existed:
  p.parent.mkdir(parents=True,exist_ok=True)
  fd,tmp=tempfile.mkstemp(prefix='.acme80-restore-',dir=p.parent);os.close(fd)
  shutil.copyfile(backup/name,tmp);os.chmod(tmp,0o600 if name=='.acme80-state.json' else 0o644);os.replace(tmp,p)
 else: p.unlink(missing_ok=True)
PY
    edge_archive_apply "$dir" false edge_npmplus_up up -d --force-recreate npmplus || return 1
    npmplus_acme_wait || return 1
    npmplus_acme_api acme-restore "$backup" || return 1
    docker exec npmplus nginx -t >/dev/null 2>&1
}

npmplus_acme_record_written() {
    python3 - "$1" "$NPMPLUS_ACME_BACKUP/written.json" <<'PY'
import hashlib,json,os,pathlib,sys
root=pathlib.Path(sys.argv[1]);result={}
for name in ['docker-compose.override.yml','templates/_common.conf','.acme80-state.json']:
 p=root/name
 if p.exists(): result[name]=hashlib.sha256(p.read_bytes()).hexdigest()
p=pathlib.Path(sys.argv[2]);p.write_text(json.dumps(result));os.chmod(p,0o600)
PY
}
