NPMPLUS_ACME_BACKUP="$TMP/rollback"
mkdir -p "$NPMPLUS_ACME_BACKUP/templates"
printf 'old override\n' > "$NPMPLUS_ACME_BACKUP/docker-compose.override.yml"
printf 'old template\n' > "$NPMPLUS_ACME_BACKUP/templates/_common.conf"
printf '{"docker-compose.override.yml":true,"templates/_common.conf":true,".acme80-state.json":false}' > "$NPMPLUS_ACME_BACKUP/files.json"
npmplus_acme_record_written "$TMP/runtime"
edge_archive_apply() { printf '%s\n' "$*" >> "$TMP/rollback-calls"; }
docker() { if [ "$1" = exec ]; then return 0; else docker_guard_spy "$@"; fi; }
npmplus_acme_rollback "$TMP/runtime" "$NPMPLUS_ACME_BACKUP"
cmp "$TMP/runtime/docker-compose.override.yml" "$NPMPLUS_ACME_BACKUP/docker-compose.override.yml"
cmp "$TMP/runtime/templates/_common.conf" "$NPMPLUS_ACME_BACKUP/templates/_common.conf"
[ ! -e "$TMP/runtime/.acme80-state.json" ]
[ "${api_modes[-1]}" = acme-restore ]
grep -q 'edge_npmplus_up up -d --force-recreate npmplus' "$TMP/rollback-calls"
npmplus_acme_record_written "$TMP/runtime"
printf 'operator edit\n' >> "$TMP/runtime/docker-compose.override.yml"
if npmplus_acme_rollback "$TMP/runtime" "$NPMPLUS_ACME_BACKUP"; then echo 'FAIL: rollback overwrote operator edit' >&2; exit 1; fi
[ "$(wc -l < "$TMP/rollback-calls")" -eq 1 ]
echo 'ok - rollback restores files through archive/API path and refuses independent edits'
python3 -B - "$ROOT" "$TMP" <<'PY'
