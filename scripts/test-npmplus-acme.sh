SPY_DIGEST=sha256:wrong
if npmplus_acme_guard "$TMP/runtime"; then echo 'FAIL: wrong image accepted' >&2; exit 1; fi
unset SPY_DIGEST
[ "$before" = "$(sha256sum "$TMP/runtime/docker-compose.override.yml" "$TMP/runtime/.acme80-state.json" "$TMP/runtime/templates/_common.conf")" ]
! grep -Eq '^(exec|restart|stop)| up ' "$TMP/docker-calls"
echo 'ok - image and source SHA guards fail before mutations'
# Env+TV mismatch must fail in the real preflight before backup/template writes.
npmplus_acme_lock() { :; }
printf '# Generated by scripts/lib/edge.sh\n' > "$TMP/runtime/docker-compose.override.yml"
NPM_ADMIN_EMAIL=admin@example.test NPM_ADMIN_PASSWORD=synthetic-only
# The node preflight is isolated at its Docker boundary; the image code isn't run.
eval "$(declare -f docker | sed '1s/docker/docker_guard_spy/')"
docker() {
    case "$1" in
        inspect) return 0 ;;
        exec)
            if [ "${2:-}" = -i ]; then cat >/dev/null; return 1; fi
            return 0 ;;
        *) docker_guard_spy "$@" ;;
    esac
}
if npmplus_acme_real_preflight "$TMP/runtime"; then echo 'FAIL: env drift accepted' >&2; exit 1; fi
[ ! -e "$TMP/backup" ]
echo 'ok - startup regeneration mismatch stops before preparation'
docker() { docker_guard_spy "$@"; }
# Real atomic preparation, with only Docker checks/backup location isolated.
npmplus_acme_preflight() { npmplus_acme_guard "$1"; }
npmplus_acme_backup() { NPMPLUS_ACME_BACKUP="$TMP/backup"; mkdir -p "$NPMPLUS_ACME_BACKUP"; }
npmplus_acme_mounted() { cmp -s "$ROOT/npmplus/templates/_common.conf" "$1/templates/_common.conf"; }
npmplus_acme_wait() { :; }
api_modes=()
npmplus_acme_api() { api_modes+=("$1"); }
rm "$TMP/runtime/templates/_common.conf"
npmplus_acme_prepare "$TMP/runtime"
[ "$NPMPLUS_ACME_CHANGED" = true ]
npmplus_acme_apply "$TMP/runtime"
[ "${api_modes[*]}" = acme-resave ]
state_before=$(sha256sum "$TMP/runtime/.acme80-state.json")
npmplus_acme_prepare "$TMP/runtime"
[ "$NPMPLUS_ACME_CHANGED" = false ]
npmplus_acme_apply "$TMP/runtime"
